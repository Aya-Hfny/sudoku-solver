"""Streamlit web interface for the Handwritten Sudoku Reader and Solver.

Input contract: a 252x252 grayscale Sudoku mosaic produced by
`data/generate_puzzles.py`. Camera-photo grid detection is not implemented.
"""
from pathlib import Path
import tempfile

import numpy as np
import pandas as pd
import streamlit as st

from nn.inference import predict_mosaic
from integration.pipeline import run_pipeline

ROOT = Path(__file__).resolve().parent
WEIGHTS = ROOT / "nn" / "artifacts" / "digit_cnn.pt"
CALIBRATION = ROOT / "nn" / "artifacts" / "calibration.json"

st.set_page_config(page_title="Handwritten Sudoku Solver", page_icon="🔢", layout="wide")
st.title("🔢 Handwritten Sudoku Reader & Solver")
st.caption("CNN digit recognition · Search-based correction · CSP solving")
st.markdown(
    "Upload a **252 × 252 grayscale mosaic** generated by this project. "
    "This version does not yet detect Sudoku grids from ordinary camera photos."
)

with st.sidebar:
    st.header("Solver settings")
    method = st.selectbox("Search algorithm", ["ucs", "greedy", "astar"],
                          format_func={"ucs": "Uniform Cost Search", "greedy": "Greedy Best-First Search", "astar": "A* Search"}.get)
    max_corrections = st.slider("Maximum digit corrections", 0, 8, 3)
    require_unique = st.checkbox("Require a unique solution", value=False)
    st.caption("The integrated pipeline uses Forward Checking and AC-3 in CSP.")

st.subheader("1. Model readiness")
if WEIGHTS.exists():
    st.success(f"CNN weights found: {WEIGHTS.relative_to(ROOT)}")
else:
    st.warning("CNN weights are not present yet. Train the model using the command below.")
    st.code(
        "python data/make_data.py --out data/processed --seed 42\n"
        "python nn/train.py --data data/processed/mnist_1_9.npz --epochs 8 --seed 42",
        language="powershell",
    )

st.subheader("2. Upload a Sudoku mosaic")
upload = st.file_uploader("Choose PNG or JPG", type=["png", "jpg", "jpeg"])
if upload is not None:
    st.image(upload, caption="Uploaded Sudoku mosaic", width=360)
    if st.button("Recognize digits and solve", type="primary", disabled=not WEIGHTS.exists()):
        temp_path = None
        try:
            suffix = Path(upload.name).suffix or ".png"
            with tempfile.NamedTemporaryFile(delete=False, suffix=suffix) as tmp:
                tmp.write(upload.getvalue())
                temp_path = Path(tmp.name)

            with st.spinner("CNN is recognizing the digits..."):
                read_grid, probabilities = predict_mosaic(
                    str(temp_path), weights_path=str(WEIGHTS),
                    temperature_path=str(CALIBRATION)
                )

            st.subheader("3. Recognized grid (0 means blank)")
            st.dataframe(pd.DataFrame(read_grid), use_container_width=True, hide_index=True)

            conf = [float(probabilities[r, c, int(read_grid[r, c]) - 1])
                    for r in range(9) for c in range(9) if read_grid[r, c] != 0]
            if conf:
                st.metric("Mean confidence of recognized digits", f"{np.mean(conf) * 100:.1f}%")

            with st.spinner("Search is checking possible corrections; CSP is solving..."):
                result = run_pipeline(
                    read_grid, probabilities, max_corrections=max_corrections,
                    method=method, require_unique=require_unique
                )

            st.subheader("4. Solver result")
            if result.get("grid") is not None:
                st.success(f"Solved: {result.get('status', 'success')}")
                solved = np.asarray(result["grid"], dtype=int)
                st.dataframe(pd.DataFrame(solved), use_container_width=True, hide_index=True)
                st.download_button(
                    "Download solution as CSV",
                    pd.DataFrame(solved).to_csv(index=False, header=False).encode("utf-8"),
                    file_name="sudoku_solution.csv", mime="text/csv"
                )
            else:
                st.error("No valid solution was found within the selected correction limit.")
                least = result.get("least_confident_cells", [])
                if least:
                    st.write("Least-confident recognized cells:")
                    st.dataframe(pd.DataFrame(least), use_container_width=True, hide_index=True)

            st.subheader("5. Correction log")
            corrections = result.get("corrections", [])
            if corrections:
                st.dataframe(pd.DataFrame(corrections), use_container_width=True, hide_index=True)
            else:
                st.info("No correction was required or returned.")

            st.subheader("6. Search and CSP statistics")
            search_stats = result.get("search", {})
            csp_stats = result.get("csp_stats", {})
            c1, c2, c3 = st.columns(3)
            c1.metric("Expanded search nodes", search_stats.get("expanded", 0))
            c2.metric("Generated search nodes", search_stats.get("generated", 0))
            cost = search_stats.get("cost", 0.0)
            c3.metric("Search cost", f"{cost:.4f}" if isinstance(cost, (int, float)) and np.isfinite(cost) else str(cost))
            if csp_stats:
                st.write("CSP counters")
                st.json(csp_stats)
            st.caption(f"Pipeline status: {result.get('status', 'unknown')}")

        except Exception as exc:
            st.exception(exc)
        finally:
            if temp_path is not None:
                temp_path.unlink(missing_ok=True)
else:
    st.info("Upload a project-generated Sudoku mosaic to begin.")

with st.expander("How to create test mosaics"):
    st.code(
        "python data/generate_puzzles.py --out data/processed/puzzles --seed 42 --count 10 --givens 35 --misreads 2",
        language="powershell",
    )
    st.write("Then upload one of the generated files, for example `data/processed/puzzles/mosaic_0000.png`.")

st.divider()
st.caption("Student project prototype. Ordinary photographed Sudoku sheets require a separate grid-localization and cell-segmentation stage.")
